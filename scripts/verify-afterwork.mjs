import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base = process.env.WAGECLAW_QA_URL || 'http://127.0.0.1:5174';
await mkdir('qa-shots', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, timezoneId: 'Asia/Shanghai' });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.clock.setFixedTime(new Date('2026-09-24T15:38:42+08:00'));
  await page.goto(base);
  await page.getByLabel('月薪', { exact: true }).fill('18000');
  await page.getByRole('button', { name: '开始我的倒计时' }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.waitForTimeout(300);
  await page.screenshot({ path: 'qa-shots/afterwork-home.png', fullPage: true });
  const panel = page.getByRole('complementary', { name: '我的桌面搭子' });
  const income = await page.getByTestId('today-income').textContent();
  for (const name of ['懒猫', '懒狗', '老实牛', '怨气团', '卡皮巴拉']) {
    await panel.getByRole('button', { name: `选择${name}`, exact: true }).click();
    await panel.getByRole('heading', { name, exact: true }).waitFor();
    await panel.getByRole('button', { name: '♡ 摸摸它', exact: true }).click();
    assert.ok((await panel.getByRole('status').textContent()).length > 8);
  }
  await panel.getByRole('button', { name: /换个形态/ }).click();
  await panel.getByRole('button', { name: '选择第 10 种形态', exact: true }).click();
  assert.equal(await panel.getByLabel('形态模式').inputValue(), '10');
  await page.reload();
  await panel.getByText('喜欢的第 10 种模样').waitFor();
  await panel.getByRole('button', { name: /换个形态/ }).click();
  await panel.getByLabel('形态模式').selectOption('auto');
  await panel.getByRole('button', { name: /换个形态/ }).click();
  await panel.getByRole('button', { name: '一起松口气', exact: true }).click();
  await page.waitForTimeout(2000);
  assert.equal(await panel.locator('canvas').evaluate(el => el.getAnimations().length), 0);
  await page.getByRole('button', { name: '放空一下 ↗' }).click();
  for (let n = 1; n <= 9; n++) await page.getByRole('button', { name: `泡泡 ${n}`, exact: true }).click();
  await page.getByText('这一小片，已经放空了。').waitFor();
  assert.equal(await page.getByTestId('today-income').textContent(), income);
  await page.getByRole('button', { name: '再来一张' }).click();
  assert.equal(await page.locator('.bubble-grid .popped').count(), 0);
  await panel.getByRole('button', { name: '今天想安静一点' }).click();
  await panel.getByRole('button', { name: '恢复偶尔播报' }).waitFor();
  await page.reload();
  await panel.getByRole('button', { name: '恢复偶尔播报' }).waitFor();
  await panel.getByRole('button', { name: '听一句', exact: true }).click();
  await panel.getByRole('button', { name: '听一句', exact: true }).click();
  await page.getByRole('button', { name: '隐藏金额', exact: true }).click();
  assert.ok(!(await panel.innerText()).includes('¥'));
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByLabel('深色外观', { exact: true }).check();
  await page.getByRole('button', { name: '保存设置' }).click();
  await page.screenshot({ path: 'qa-shots/afterwork-dark.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'qa-shots/afterwork-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => globalThis.document.documentElement.scrollWidth <= globalThis.innerWidth));
  const preview = await context.newPage(); await preview.goto(`${base}/?view=pet-preview`);
  await preview.getByRole('button', { name: /卡皮巴拉 Lv\./ }).waitFor();
  await panel.getByRole('button', { name: '选择懒猫', exact: true }).click();
  await preview.getByRole('button', { name: /懒猫 Lv\./ }).waitFor();
  assert.deepEqual(errors, []);
  console.log('Afterwork: all five pets, fixed/auto forms, persistence, reactions, finite motion, bubbles without changing earnings, quiet mode, privacy, dark/mobile layout, cross-tab preview sync passed.');
} finally { await browser.close(); }
